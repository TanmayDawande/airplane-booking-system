-- 3. Assessment 9 - important queries
-- ------------------------------------------------------------------------------
-- Five-table INNER JOIN: full itinerary
SELECT
    b.pnr,
    CONCAT(p.first_name, ' ', p.last_name) AS passenger_name,
    al.airline_name,
    f.flight_number,
    orig.city AS origin_city,
    dest.city AS dest_city,
    f.departure_time,
    b.seat_number,
    b.travel_class,
    b.total_amount,
    b.status AS booking_status,
    b.booking_date
FROM bookings b
JOIN passengers p ON b.passenger_id = p.passenger_id
JOIN flights f ON b.flight_id = f.flight_id
JOIN airlines al ON f.airline_id = al.airline_id
JOIN airports orig ON f.origin_code = orig.airport_code
JOIN airports dest ON f.destination_code = dest.airport_code
ORDER BY b.booking_id DESC;

-- GROUP BY + HAVING
SELECT
    al.airline_name,
    COUNT(b.booking_id) AS total_bookings,
    SUM(b.total_amount) AS gross_revenue,
    ROUND(AVG(b.total_amount), 2) AS average_fare
FROM airlines al
JOIN flights f ON al.airline_id = f.airline_id
JOIN bookings b ON f.flight_id = b.flight_id
WHERE b.status = 'CONFIRMED'
GROUP BY al.airline_id, al.airline_name
HAVING gross_revenue > 5000
ORDER BY gross_revenue DESC;

-- Nested subquery
SELECT
    p.passenger_id,
    CONCAT(p.first_name, ' ', p.last_name) AS full_name,
    p.email,
    b.pnr,
    b.total_amount
FROM passengers p
JOIN bookings b ON p.passenger_id = b.passenger_id
WHERE b.status = 'CONFIRMED'
  AND b.total_amount > (
      SELECT AVG(total_amount) FROM bookings WHERE status = 'CONFIRMED'
  )
ORDER BY b.total_amount DESC;

-- Seat occupancy and calculated percentage
SELECT
    f.flight_number,
    al.airline_name,
    ac.total_seats,
    COUNT(CASE WHEN b.status = 'CONFIRMED' THEN b.booking_id END) AS booked,
    (ac.total_seats - COUNT(CASE WHEN b.status = 'CONFIRMED' THEN b.booking_id END)) AS available,
    ROUND((COUNT(CASE WHEN b.status = 'CONFIRMED' THEN b.booking_id END) * 100.0 / ac.total_seats), 2) AS occupancy_pct
FROM flights f
JOIN airlines al ON f.airline_id = al.airline_id
JOIN aircrafts ac ON f.aircraft_id = ac.aircraft_id
LEFT JOIN bookings b ON f.flight_id = b.flight_id
GROUP BY f.flight_id, f.flight_number, al.airline_name, ac.total_seats
ORDER BY booked DESC;

